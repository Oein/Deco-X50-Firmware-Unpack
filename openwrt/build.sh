#!/bin/sh
# Build an OpenWrt image for the TP-Link Deco X50 v1 inside Docker.
#
# The OpenWrt tree lives in a Docker volume (case-sensitive filesystem,
# which macOS bind mounts are not); finished images are copied to ./bin.
#
# Wi-Fi is enabled on first boot with one SSID on both bands:
#   WIFI_SSID    (default X50-OpenWrt)
#   WIFI_KEY     (default: none, an open network; set it for WPA2)
#   WIFI_COUNTRY (default US)
# The values end up in the image and in bin/wifi-credentials.txt.
set -e

OPENWRT_REPO=https://github.com/openwrt/openwrt.git
OPENWRT_COMMIT=b3d6d595fff76fd42be7333f0e6dba2ffa1295d2
JOBS=${JOBS:-$(nproc 2>/dev/null || sysctl -n hw.ncpu)}

WIFI_SSID=${WIFI_SSID:-X50-OpenWrt}
WIFI_KEY=${WIFI_KEY:-}
WIFI_COUNTRY=${WIFI_COUNTRY:-US}
WIFI_ENCRYPTION=none
[ -z "$WIFI_KEY" ] || WIFI_ENCRYPTION=psk2

case "$WIFI_SSID$WIFI_KEY$WIFI_COUNTRY" in
*[\'\"\\\`\$]*)
	echo "WIFI_SSID, WIFI_KEY and WIFI_COUNTRY must not contain quotes, \\, \` or \$" >&2
	exit 1
	;;
esac
if [ -n "$WIFI_KEY" ] && { [ ${#WIFI_KEY} -lt 8 ] || [ ${#WIFI_KEY} -gt 63 ]; }; then
	echo "WIFI_KEY must be 8 to 63 characters" >&2
	exit 1
fi

cd "$(dirname "$0")"

docker build -t deco-x50-openwrt-builder .
docker volume create deco-x50-openwrt-src >/dev/null
mkdir -p bin

docker run --rm \
	-v deco-x50-openwrt-src:/src \
	-v "$PWD":/patches:ro \
	-v "$PWD/bin":/out \
	-e OPENWRT_REPO="$OPENWRT_REPO" \
	-e OPENWRT_COMMIT="$OPENWRT_COMMIT" \
	-e JOBS="$JOBS" \
	-e WIFI_SSID="$WIFI_SSID" \
	-e WIFI_KEY="$WIFI_KEY" \
	-e WIFI_ENCRYPTION="$WIFI_ENCRYPTION" \
	-e WIFI_COUNTRY="$WIFI_COUNTRY" \
	deco-x50-openwrt-builder sh -ec '
		if [ ! -d openwrt/.git ]; then
			git clone "$OPENWRT_REPO" openwrt
		fi
		cd openwrt
		git checkout -f "$OPENWRT_COMMIT"
		git clean -fd target package
		git apply /patches/0001-qualcommax-ipq50xx-add-TP-Link-Deco-X50-v1.patch

		# board data generated by make-board2.py (kept out of git)
		if [ -d /patches/wifi-board ]; then
			mkdir -p package/firmware/ipq-wifi/files
			cp /patches/wifi-board/* package/firmware/ipq-wifi/files/
		fi

		# Wi-Fi defaults, applied when board.json is generated on first boot
		rm -rf files
		mkdir -p files/etc/board.d
		cat > files/etc/board.d/99_wifi_defaults <<WIFI
#!/bin/sh
. /lib/functions/uci-defaults.sh

board_config_update
ucidef_set_wireless all "$WIFI_SSID" "$WIFI_ENCRYPTION" "$WIFI_KEY"
ucidef_set_country "$WIFI_COUNTRY"
board_config_flush

exit 0
WIFI
		chmod 755 files/etc/board.d/99_wifi_defaults

		./scripts/feeds update -a
		./scripts/feeds install -a

		cat > .config <<EOF
CONFIG_TARGET_qualcommax=y
CONFIG_TARGET_qualcommax_ipq50xx=y
CONFIG_TARGET_qualcommax_ipq50xx_DEVICE_tplink_deco-x50-v1=y
CONFIG_TARGET_ROOTFS_INITRAMFS=y
CONFIG_PACKAGE_luci=y
EOF
		make defconfig
		make -j"$JOBS" download
		make -j"$JOBS" || make -j1 V=s

		cp -v bin/targets/qualcommax/ipq50xx/*deco-x50-v1* /out/
	'

cat > bin/wifi-credentials.txt <<EOF
SSID:       $WIFI_SSID
Encryption: $WIFI_ENCRYPTION
Key:        ${WIFI_KEY:-(none)}
Country:    $WIFI_COUNTRY
EOF
echo "Wi-Fi: SSID '$WIFI_SSID', encryption $WIFI_ENCRYPTION (saved to bin/wifi-credentials.txt)"
